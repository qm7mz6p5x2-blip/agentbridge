#!/usr/bin/env node

const fs = require("fs").promises;
const path = require("path");

const PROJECT_ROOT = path.resolve(__dirname, "..");
const DEFAULT_PLUGINS_DIR = path.join(PROJECT_ROOT, "workspace", "plugins");

function validateId(value) {
  return /^[a-zA-Z0-9_-]+$/.test(value);
}

function toToolName(value) {
  return value
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9_]+/g, "_")
    .replace(/^_+|_+$/g, "");
}

function buildPluginFiles(options) {
  const { id, name, toolName, description } = options;
  const manifest = {
    id,
    name,
    version: "0.1.0",
    description,
    entry: "index.js",
    requiredEngineVersion: "^0.2.0",
    tools: [toolName],
    kind: "tool",
    permissions: {
      filesystem: true,
      network: false,
      child_process: false,
    },
  };

  const index = `module.exports = function register(api) {
  api.logger.info("[${id}] plugin loaded");

  api.registerTool(function () {
    return [{
      name: "${toolName}",
      label: "${name}",
      description: "${description}",
      parameters: {
        type: "object",
        properties: {
          message: {
            type: "string",
            description: "Message passed to the example tool"
          }
        },
        required: []
      },
      execute: async function (args) {
        return JSON.stringify({
          success: true,
          tool: "${toolName}",
          message: args.message || "Hello from ${name}"
        });
      }
    }];
  });
};
`;

  const readme = `# ${name}

Generated by the AgentBridge plugin SDK.

Tool name: \`${toolName}\`

## Install

Copy this directory under \`workspace/plugins/\` and reload plugins.

## Development

Edit \`index.js\` and keep each tool's \`name\`, \`description\`, \`parameters\`, and
\`execute\` fields explicit so the model can call it safely.
`;

  return {
    "plugin.json": JSON.stringify(manifest, null, 2) + "\n",
    "index.js": index,
    "README.md": readme,
  };
}

async function createPlugin(options) {
  const pluginsDir = options.pluginsDir || DEFAULT_PLUGINS_DIR;
  const id = (options.id || "").trim();
  const name = (options.name || id).trim();
  const toolName = toToolName(options.toolName || id + "_tool");
  const description = options.description || name + " example tool";

  if (!validateId(id)) {
    throw new Error("插件 ID 只能包含字母、数字、下划线和连字符");
  }
  if (!validateId(toolName)) {
    throw new Error("工具名只能包含字母、数字、下划线和连字符");
  }

  const pluginDir = path.join(pluginsDir, id);
  try {
    await fs.access(pluginDir);
    throw new Error("插件目录已存在: " + pluginDir);
  } catch (e) {
    if (e.code !== "ENOENT") throw e;
  }

  await fs.mkdir(pluginDir, { recursive: true });
  const files = buildPluginFiles({ id, name, toolName, description });
  for (const [fileName, content] of Object.entries(files)) {
    await fs.writeFile(path.join(pluginDir, fileName), content, "utf-8");
  }

  return { pluginDir, toolName, files: Object.keys(files) };
}

function parseArgs(argv) {
  const options = { id: argv[0] || "" };
  for (let i = 1; i < argv.length; i++) {
    const token = argv[i];
    if (token === "--name") options.name = argv[++i];
    else if (token === "--tool") options.toolName = argv[++i];
    else if (token === "--description") options.description = argv[++i];
    else if (token === "--plugins-dir") options.pluginsDir = argv[++i];
  }
  return options;
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  if (!options.id) {
    console.error("Usage: node sdk/create-plugin.js <plugin-id> --name <name> --tool <tool_name>");
    process.exit(1);
  }
  const result = await createPlugin(options);
  console.log("Created plugin: " + result.pluginDir);
  console.log("Registered tool: " + result.toolName);
}

if (require.main === module) {
  main().catch((error) => {
    console.error(error.message);
    process.exit(1);
  });
}

module.exports = {
  buildPluginFiles,
  createPlugin,
  parseArgs,
  toToolName,
};
